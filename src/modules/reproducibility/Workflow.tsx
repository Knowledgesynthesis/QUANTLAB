import { useState } from 'react';
import { Download } from 'lucide-react';
import { Button, Callout, Checkbox, Code, DataTable, Stat } from '@/components/ui';
import { CheckYourself, Cite, Lab, P, Takeaways } from '@/components/learning';
import { downloadText, pct } from '@/lib/utils';

const items: { group: string; text: string; weight: number }[] = [
  { group: 'Data', text: 'Raw data are read-only and stored outside version control (or encrypted)', weight: 2 },
  { group: 'Data', text: 'A data dictionary exists and is versioned with the code', weight: 2 },
  { group: 'Data', text: 'Every cleaning step is scripted; counts are logged', weight: 3 },
  { group: 'Code', text: 'The full analysis runs from raw data with one command (targets, make, snakemake)', weight: 3 },
  { group: 'Code', text: 'Code is under version control with meaningful commit messages', weight: 2 },
  { group: 'Code', text: 'Random seeds are set for every stochastic step', weight: 2 },
  { group: 'Code', text: 'No hard-coded absolute paths (use project-relative paths, e.g., here::here)', weight: 1 },
  { group: 'Environment', text: 'Package versions are locked (renv.lock, uv.lock, conda-lock)', weight: 3 },
  { group: 'Environment', text: 'R/Python version and OS are recorded', weight: 1 },
  { group: 'Environment', text: 'A container or image is archived for long-term reuse', weight: 1 },
  { group: 'Reporting', text: 'Tables and figures are generated by code, not copied by hand', weight: 3 },
  { group: 'Reporting', text: 'The manuscript numbers come from a rendered document (Quarto/R Markdown)', weight: 2 },
  { group: 'Reporting', text: 'A statistical analysis plan was dated before outcome data were analysed', weight: 2 },
  { group: 'Sharing', text: 'Code is publicly archived with a DOI (e.g., Zenodo) at publication', weight: 2 },
  { group: 'Sharing', text: 'Data, or a synthetic version with the same structure, are shared where governance allows', weight: 1 },
];

export default function Workflow() {
  const [done, setDone] = useState<boolean[]>(items.map(() => false));
  const total = items.reduce((s, i) => s + i.weight, 0);
  const score = items.reduce((s, it, k) => s + (done[k] ? it.weight : 0), 0);
  const exportMd = () => {
    const lines = ['# Reproducibility self-audit', '', `Score: ${score}/${total}`, '', ...items.map((it, k) => `- [${done[k] ? 'x' : ' '}] (${it.group}) ${it.text}`)];
    downloadText('reproducibility-audit.md', lines.join('\n'), 'text/markdown');
  };
  return (
    <div>
      <P>
        A reproducible project is organised so that someone else, including you in a year, can rebuild every number in the paper from the raw data with one command
        <Cite ids="sandve2013,peng2011" />.
      </P>
      <Code
        title="A project layout that works (R or Python)"
        r={`my-study/\n├── README.md            # question, how to run, data access\n├── renv.lock            # exact package versions  (renv::snapshot())\n├── _targets.R           # pipeline: raw → clean → models → tables\n├── data/\n│   ├── raw/             # read-only; in .gitignore if identifiable\n│   └── derived/         # created by code only\n├── R/                   # functions: clean.R, models.R, figures.R\n├── analysis/\n│   └── manuscript.qmd   # Quarto: text + code + numbers\n├── docs/\n│   ├── data-dictionary.csv\n│   └── SAP_v1.0_2025-03-01.pdf\n└── output/              # tables/, figures/ (generated)`}
        py={`my-study/\n├── README.md\n├── pyproject.toml       # dependencies\n├── uv.lock              # exact versions  (uv lock)\n├── Snakefile            # or Makefile: raw → clean → models → tables\n├── data/raw/            # read-only; in .gitignore if identifiable\n├── data/derived/\n├── src/study/           # clean.py, models.py, figures.py\n├── analysis/manuscript.qmd\n├── docs/data-dictionary.csv\n└── output/`}
      />
      <DataTable
        head={['Tool', 'Purpose', 'R', 'Python']}
        rows={[
          ['Version control', 'History of every change; collaboration', 'Git (+ GitHub/GitLab)', 'Git'],
          ['Environment lock', 'Restore exact package versions', 'renv', 'uv, pip-tools, conda-lock'],
          ['Pipeline', 'Re-run only what changed, in the right order', 'targets', 'snakemake, make, DVC'],
          ['Literate document', 'Numbers in text come from code', 'Quarto', 'Quarto, Jupyter'],
          ['Data validation', 'Fail loudly when data change', 'validate, pointblank', 'pandera'],
          ['Containers', 'Archive the full OS + software stack', 'Rocker images', 'Docker'],
          ['Archiving', 'Citable, permanent snapshot', 'Zenodo / OSF DOI', 'Zenodo / OSF DOI'],
        ]}
      />
      <Callout kind="mistake" title="Committing patient data">
        Git keeps every version forever, and repositories get forked and mirrored. Identifiable data never go into version control; add <code>data/raw/</code> to
        <code> .gitignore</code> before the first commit. Share code, the dictionary and, where useful, synthetic data <Cite ids="wilkinson2016" />.
      </Callout>
      <Lab title="Project self-audit" description="Tick what is true for your current project." actions={<Button size="sm" variant="outline" onClick={exportMd}><Download className="h-4 w-4" /> Export</Button>}>
        <div className="grid grid-cols-2 gap-3">
          <Stat label="Score" value={`${score} / ${total}`} tone={score / total >= 0.8 ? 'good' : score / total >= 0.5 ? 'warning' : 'critical'} />
          <Stat label="Coverage" value={pct(score / total)} />
        </div>
        {['Data', 'Code', 'Environment', 'Reporting', 'Sharing'].map((g) => (
          <fieldset key={g} className="space-y-2">
            <legend className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted-foreground">{g}</legend>
            {items.map((it, k) => it.group === g && (
              <Checkbox key={k} label={it.text} checked={done[k]} onChange={(v) => setDone((d) => d.map((x, j) => (j === k ? v : x)))} hint={it.weight >= 3 ? 'High impact' : undefined} />
            ))}
          </fieldset>
        ))}
      </Lab>
      <Code
        title="Getting started in 10 minutes"
        r={`usethis::create_project("my-study"); usethis::use_git()\nrenv::init()                       # project library + renv.lock\nusethis::use_git_ignore("data/raw/")\ntargets::use_targets()             # pipeline skeleton\n# ...work...\nrenv::snapshot(); targets::tar_make()`}
        py={`uv init my-study && cd my-study && git init\nuv add pandas statsmodels scikit-learn pandera\necho "data/raw/" >> .gitignore\nuv lock                             # exact versions in uv.lock\nuv run python -m study.pipeline`}
      />
      <Takeaways
        items={[
          'One command should rebuild everything from raw data.',
          'Lock package versions and keep data out of Git.',
          'Generate tables, figures and in-text numbers from code.',
          'Archive code with a DOI at publication.',
        ]}
      />
      <CheckYourself ids={['rp-git-phi', 'rp-lockfile']} />
    </div>
  );
}
